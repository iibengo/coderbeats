// Estudio · editor de melodía (spec 020 §1): tocar casillas, quitar, cambiar altura, alargar arrastrando, largo 1/2/4, deshacer, y que la melodía llegue al loop del motor.
import { open, clickLabel, sleep } from './lib.mjs'
const O = process.env.OUT || '/tmp'
const { b, p, errs } = await open()
console.log('abre el editor:', await clickLabel(p, 'editor de melodía')); await sleep(800)
const g = await p.evaluate(() => { const r = document.querySelector('[data-grid]').getBoundingClientRect(); return [r.x, r.y, r.width, r.height] })
const cell = (c, rowFromTop) => [g[0] + ((c + 0.5) / 8) * g[2], g[1] + ((rowFromTop + 0.5) / 9) * g[3]]
const hits = () => p.evaluate(() => JSON.stringify(window.__melody.hits()))
const loops = () => p.evaluate(() => window.__engine.loops.value.loops.filter((l) => l.instrument === 'mel').map((l) => [l.bars, l.hits.length]))
console.log('al abrir:', await hits(), 'largo', await p.evaluate(() => window.__melody.bars()))
await p.mouse.click(...cell(0, 4)); await sleep(150)
await p.mouse.click(...cell(2, 3)); await sleep(150)
await p.mouse.click(...cell(4, 5)); await sleep(150)
console.log('3 casillas:', await hits(), '| loops de melodía en el motor:', JSON.stringify(await loops()))
await p.mouse.click(...cell(2, 3)); await sleep(150)
console.log('quito la 2.ª:', await hits())
await p.mouse.click(...cell(4, 1)); await sleep(150)
console.log('misma columna, otra altura:', await hits())
// alargar arrastrando de la columna 0 a la 3
const [sx, sy] = cell(0, 4)
await p.mouse.move(sx, sy); await p.mouse.down(); await p.mouse.move(...cell(3, 4), { steps: 6 }); await p.mouse.up(); await sleep(150)
console.log('arrastrar desde la nota de la columna 0 hasta la 3 (se alarga):', await hits())
await clickLabel(p, 'deshacer'); await sleep(100)
console.log('(deshacer del alargado)')
console.log('deshacer:', await hits())
await p.screenshot({ path: `${O}/editor1.png` })
await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === '4')?.click()); await sleep(200)
console.log('largo 4:', await p.evaluate(() => window.__melody.bars()), JSON.stringify(await loops()))
await clickLabel(p, 'compás siguiente'); await sleep(100)
await p.mouse.click(...cell(1, 2)); await sleep(150)
console.log('nota en el compás 2:', await hits())
await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === '1')?.click()); await sleep(200)
console.log('largo 1 (lo de fuera se quita):', await hits(), await p.evaluate(() => window.__melody.bars()))
await p.evaluate(() => document.querySelector('[role=dialog] button[aria-label=tocar]')?.click()); await sleep(3500)
await p.screenshot({ path: `${O}/editor2.png` })
console.log('sonando:', await p.evaluate(() => window.__engine.playing.value), errs)
await b.close()
