// La guía de la portada, paso a paso, y el tiempo hasta tener música (criterios de §8 de la spec 016).
import { open, sleep, clickLabel } from './lib.mjs'
const OUT = process.env.OUT || '/tmp'
const t0 = Date.now()
const { b, p, errs } = await open({ simple: true })
const line = () => p.evaluate(() => document.querySelector('[data-guide]')?.textContent.trim() ?? '(ninguna)')
console.log('1 · al abrir:', (await p.evaluate(() => document.querySelector('h1')?.textContent)))
await clickLabel(p, 'Hip hop')
const tMusic = Date.now()
await p.waitForFunction(() => window.__engine?.playing?.value === true, { timeout: 8000 })
console.log('música sonando', ((Date.now() - tMusic) / 1000).toFixed(1), 's después de elegir estilo')
await sleep(800)
console.log('2 ·', await line())
console.log('   (la espiral aún no está:', !(await p.evaluate(() => !!document.querySelector('.th'))), ')')
const box = await p.evaluate(() => { const r = [...document.querySelectorAll('button')].find((x) => x.getAttribute('aria-label') === 'bum').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
await p.touchscreen.tap(box.x, box.y); await sleep(700)
console.log('3 ·', await line(), '| espiral ya:', await p.evaluate(() => !!document.querySelector('.th')))
await p.waitForSelector('.th', { timeout: 9000 })
const t = await p.touchscreen.touchStart(200, 300); await sleep(600)
await t.end(); await sleep(300)
console.log('4 ·', await line())
await p.screenshot({ path: `${OUT}/portada-5.png` })
await sleep(7500)
console.log('5 · tras 7 s:', await line(), '| guía guardada:', await p.evaluate(() => localStorage.getItem('coderbeats:portada:guide:v1')))
console.log('errores', errs)
await b.close()
