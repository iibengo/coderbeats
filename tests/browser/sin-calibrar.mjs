// Sin calibración (spec 001 §17): Empezar lleva directo al Estudio, con el modelo por defecto, latencia por defecto y los golpes del micro de mentira se clasifican.
import puppeteer from 'puppeteer-core'
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', '--autoplay-policy=no-user-gesture-required'] })
const p = await b.newPage()
await p.setViewport({ width: 400, height: 800, deviceScaleFactor: 1, hasTouch: true, isMobile: true })
const errs = []
p.on('pageerror', (e) => errs.push(String(e).slice(0, 300)))
await p.goto(`http://localhost:${process.env.PORT || 3999}/estudio`, { waitUntil: 'networkidle2', timeout: 120000 })
await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.includes('Empezar'))?.click())
await sleep(7000)
const labels = await p.$$eval('button', (bs) => bs.filter((b) => b.offsetParent !== null).map((b) => (b.getAttribute('aria-label') || b.textContent).trim().slice(0, 30)))
console.log('estudio directo:', labels.includes('tocar'), '| pantalla de latencia:', await p.evaluate(() => document.body.textContent.includes('Latencia')))
console.log('modelo propio:', await p.evaluate(() => window.__engine.personalModel.value), '| latencia usada ms:', await p.evaluate(() => Math.round(window.__engine.roundTripMs?.value ?? -1)))
await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.getAttribute('aria-label') === 'tocar')?.click())
await sleep(6000)
console.log('golpes oídos por el modelo por defecto:', await p.evaluate(() => window.__engine.diag.value.filter((d) => d.kind === 'hit').length), 'bolas:', await p.evaluate(() => window.__engine.loops.value.loops.map((l) => l.instrument).join(',')))
console.log('ejemplo de línea:', await p.evaluate(() => window.__engine.diag.value.find((d) => d.kind === 'hit')?.text))
await p.screenshot({ path: process.env.OUT + '/s1.png' })
await p.evaluate(() => { window.__engine.calibNudge.value = true })
await sleep(400)
await p.screenshot({ path: process.env.OUT + '/s2.png' })
await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Sí')?.click())
await sleep(800)
console.log('«Sí» lleva a Tus sonidos:', await p.evaluate(() => document.body.textContent.includes('Tus sonidos')), '| «Ahora no» presente:', await p.evaluate(() => document.body.textContent.includes('Ahora no')))
console.log(errs)
await b.close()
